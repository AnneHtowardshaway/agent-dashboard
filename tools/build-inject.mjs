#!/usr/bin/env node
// Build the single-file bundle injected through CDP into Codex.
// The shared Antigravity widget stays untouched; this only supplies the host
// bridge (Runtime binding RPC), the i18n/theme factories and the DOM surface.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const PREFIX = 'module.exports = ';

function factory(file) {
  const source = readFileSync(join(root, 'compat', file), 'utf8');
  const index = source.indexOf(PREFIX);
  if (index < 0) throw new Error(`${file} is not a CommonJS factory`);
  return source.slice(index + PREFIX.length).trim().replace(/;\s*$/, '');
}

const i18n = factory('i18n.cjs');
const theme = factory('theme.cjs');
const surface = factory('multi-host-surface.cjs');
const inline = factory('inline-widget.cjs');

const rev = String(Date.now());
const bundle = `/* generated by tools/build-inject.mjs — do not edit */
(function () {
  if (window.__agPulseInjected) return;
  window.__agPulseInjected = true;
  window.__AG_PULSE_BUNDLE_REV = ${rev};
  var HOST = window.__AG_PULSE_HOST__ || 'codex';
  var pending = new Map();
  var sequence = 0;
  function offline(message) {
    return { connection: 'offline', error: message, groups: [], speed: null, serverTime: new Date().toISOString() };
  }
  function request(op, input) {
    return new Promise(function (resolve) {
      var id = ++sequence;
      pending.set(id, resolve);
      try {
        window.__agPulseSend(JSON.stringify({ id: id, op: op, input: input || {} }));
      } catch (error) {
        pending.delete(id);
        resolve(offline('Multi-host bridge unavailable'));
        return;
      }
      setTimeout(function () {
        if (pending.delete(id)) resolve(offline('Multi-host bridge timeout'));
      }, 15000);
    });
  }
  window.agPulseHost = {
    getMetrics: function (input) { return request('metrics', input || {}); },
    getPreferences: function () { return request('preferences', {}); },
    setPreferences: function (input) { return request('preferences', input || {}); },
    report: function () {},
  };
  window.__agPulseResolve = function (payload) {
    var message;
    try { message = JSON.parse(payload); } catch (error) { return; }
    var resolve = pending.get(message.id);
    if (resolve) { pending.delete(message.id); resolve(message.result); }
  };
  window.__agPulseI18nFactory = (${i18n});
  window.__agPulseThemeFactory = (${theme});
  window.__agPulseSurface = (${surface})({ host: HOST });
  (${inline})();
})();
`;

mkdirSync(join(root, 'compat'), { recursive: true });
const output = join(root, 'compat', 'inject-bundle.js');
writeFileSync(output, bundle, 'utf8');
console.log(`Wrote ${output} (${Buffer.byteLength(bundle)} bytes)`);
